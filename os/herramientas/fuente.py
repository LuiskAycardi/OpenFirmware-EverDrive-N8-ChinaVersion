def tile(dibujo):
    filas = dibujo.split('|')
    assert len(filas) == 7 and all(len(f) == 5 for f in filas), dibujo
    plano0 = [sum(1 << (7 - i) for i, c in enumerate(f) if c == '#') for f in filas] + [0]
    return bytes(plano0) + bytes(8)


def main():
    salida = bytearray()
    for c in range(0x20, 0x60):
        salida += tile(G[chr(c)])
    assert len(salida) == 64 * 16
    open(sys.argv[1], 'wb').write(salida)


if __name__ == '__main__':
    main()
