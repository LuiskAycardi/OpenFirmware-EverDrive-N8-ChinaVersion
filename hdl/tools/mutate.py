hdl = pathlib.Path(__file__).resolve().parent.parent
rtl_files = sorted((hdl / "rtl").glob("*.v"))


def run(m):
    desc, fname, old, new, tb = m
    with tempfile.TemporaryDirectory() as tmp:
        tmp = pathlib.Path(tmp)
        srcs = []
        for f in rtl_files:
            text = f.read_text()
            if f.name == fname:
                if old not in text:
                    return f"[{desc}] ERROR: no se encontró el texto a mutar", False
                text = text.replace(old, new, 1)
            dst = tmp / f.name
            dst.write_text(text)
            srcs.append(str(dst))
        vvp = tmp / "t.vvp"
        r = subprocess.run(["iverilog", "-g2005", "-I", str(hdl / "sim"), "-o", str(vvp),
                            str(hdl / "sim" / f"{tb}.v"), *srcs], capture_output=True, text=True)
        if r.returncode != 0:
            return f"[{desc}] ERROR de compilación: {r.stderr.strip()[:200]}", False
        out = subprocess.run(["vvp", "-n", str(vvp)], cwd=tmp, capture_output=True, text=True, errors="replace").stdout
        fallos = out.count("FALLO")
        estado = "detectada" if fallos else "NO DETECTADA"
        return f"[{estado:12s}] {desc}: {fallos} fallos", fallos > 0


if __name__ == "__main__":
    import concurrent.futures
    import os
    jobs = int(os.environ.get("JOBS", os.cpu_count() or 1))
    ok = True
    with concurrent.futures.ThreadPoolExecutor(max_workers=jobs) as ex:
        for line, good in ex.map(run, MUTATIONS):
            print(line, flush=True)
            ok &= good
    print(f"{sum(1 for _ in MUTATIONS)} mutaciones")
    sys.exit(0 if ok else 1)
