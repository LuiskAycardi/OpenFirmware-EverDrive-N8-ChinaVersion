#!/usr/bin/env python3
"""gen_vrc7_tables.py — writes hdl/rtl/vrc7_tables.v (ROM tables of the VRC7 FM synth, vrc7_fm.v).

Sources (facts, not code):
  - log-sine and exponent tables from their formulas (YM2413 notes by andete; used by emu2413):
      sin[x] = round(-log2(sin((x + 0.5) * pi / 512)) * 256),   x = 0..255 (quarter wave)
      exp[x] = round((2 ** (x / 256) - 1) * 1024),              x = 0..255
  - VRC7 built-in instrument set measured by Nuke.YKT,
  - AM LFO pattern, PM table, envelope step patterns and key-scale levels of the YM2413 family.
Every table is checked against the corresponding array of the bench oracle (emu2413 in tools/mesen2)
before writing, so the hardware tables are exactly the oracle's.
  python3 -I tools/fm/gen_vrc7_tables.py
"""
import math
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parents[2]
ORACLE = ROOT / "tools/mesen2/Core/Shared/Utilities/emu2413.cpp"
OUT = ROOT / "hdl/rtl/vrc7_tables.v"

SIN = [round(-math.log2(math.sin((x + 0.5) * math.pi / 512)) * 256) for x in range(256)]
EXP = [round((2 ** (x / 256) - 1) * 1024) for x in range(256)]

# VRC7 instruments 1-15 (8 bytes each, same layout as the user patch registers $00-$07)
VRC7 = [
    [0x03, 0x21, 0x05, 0x06, 0xe8, 0x81, 0x42, 0x27],
    [0x13, 0x41, 0x14, 0x0d, 0xd8, 0xf6, 0x23, 0x12],
    [0x11, 0x11, 0x08, 0x08, 0xfa, 0xb2, 0x20, 0x12],
    [0x31, 0x61, 0x0c, 0x07, 0xa8, 0x64, 0x61, 0x27],
    [0x32, 0x21, 0x1e, 0x06, 0xe1, 0x76, 0x01, 0x28],
    [0x02, 0x01, 0x06, 0x00, 0xa3, 0xe2, 0xf4, 0xf4],
    [0x21, 0x61, 0x1d, 0x07, 0x82, 0x81, 0x11, 0x07],
    [0x23, 0x21, 0x22, 0x17, 0xa2, 0x72, 0x01, 0x17],
    [0x35, 0x11, 0x25, 0x00, 0x40, 0x73, 0x72, 0x01],
    [0xb5, 0x01, 0x0f, 0x0f, 0xa8, 0xa5, 0x51, 0x02],
    [0x17, 0xc1, 0x24, 0x07, 0xf8, 0xf8, 0x22, 0x12],
    [0x71, 0x23, 0x11, 0x06, 0x65, 0x74, 0x18, 0x16],
    [0x01, 0x02, 0xd3, 0x05, 0xc9, 0x95, 0x03, 0x02],
    [0x61, 0x63, 0x0c, 0x00, 0x94, 0xc0, 0x33, 0xf6],
    [0x21, 0x72, 0x0d, 0x00, 0xc1, 0xd5, 0x56, 0x06],
]

# AM LFO: levels 0..12 held 8 steps, 13 held 3 steps, back down 12..1 for 8 steps and 0 for 7 (210 steps)
AM = []
for v in range(13):
    AM += [v] * 8
AM += [13] * 3
for v in range(12, 0, -1):
    AM += [v] * 8
AM += [0] * 7

# key-scale level base in units of 0.375 dB*2 ("dB2"): 0, 9, 12, 13.875 ... 21 dB
KL_DB = [0.0, 9.0, 12.0, 13.875, 15.0, 16.125, 16.875, 17.625, 18.0, 18.75, 19.125, 19.5, 19.875, 20.25,
         20.625, 21.0]


def klpart(fnum4, blk, kl):
    """Key-scale attenuation added to TL*2 (envelope units of 0.375 dB)."""
    if kl == 0:
        return 0
    tmp = int(KL_DB[fnum4] * 2 - 6.0 * (7 - blk))          # C truncation toward zero
    if tmp <= 0:
        return 0
    return int((tmp >> (3 - kl)) / 0.375)


def c_array(name):
    src = ORACLE.read_text()
    m = re.search(r"\b" + name + r"\s*\[[^\]]*\](?:\[[^\]]*\])*\s*=\s*\{(.*?)\};", src, re.S)
    body = re.sub(r"/\*.*?\*/", "", re.sub(r"//[^\n]*", "", m.group(1)), flags=re.S)
    return [int(t, 0) for t in re.findall(r"-?0x[0-9a-fA-F]+|-?\d+", body)]


def check():
    full = c_array("fullsin_table")
    assert SIN == full[:256], "sine table differs from the oracle"
    assert EXP == c_array("exp_table"), "exp table differs from the oracle"
    assert AM == c_array("am_table"), "AM table differs from the oracle"
    inst = c_array("default_inst")
    vrc7 = inst[19 * 8: 19 * 8 * 2]                      # second preset set (VRC7)
    flat = [b for p in VRC7 for b in p]
    assert vrc7[8:8 + 15 * 8] == flat, "VRC7 instruments differ from the oracle"


def case(fn, width, values, abits, comment):
    lines = [f"    // {comment}", f"    function [{width - 1}:0] {fn};", f"        input [{abits - 1}:0] a;",
             f"        case (a)"]
    for i, v in enumerate(values):
        lines.append(f"            {abits}'d{i}: {fn} = {width}'d{v};")
    lines += [f"            default: {fn} = {width}'d0;", "        endcase", "    endfunction"]
    return "\n".join(lines)


def main():
    check()
    patch = [b for p in VRC7 for b in p]
    kl = [klpart(i & 15, (i >> 4) & 7, (i >> 7) & 3) for i in range(512)]
    v = []
    v.append("`timescale 1ns/1ps")
    v.append("// vrc7_tables.v — GENERATED by tools/fm/gen_vrc7_tables.py; do not edit by hand.")
    v.append("// ROM tables of the VRC7 FM synth (vrc7_fm.v). See the generator for sources and the oracle check.")
    v.append("")
    v.append("// Quarter-wave log-sine (12 bits) and exponent (10 bits), registered outputs (M4K ROMs).")
    v.append("module vrc7_sinrom (input wire clk, input wire [7:0] a, output reg [11:0] q);")
    v.append(case("f", 12, SIN, 8, "-log2(sin) * 256"))
    v.append("    always @(posedge clk) q <= f(a);")
    v.append("endmodule")
    v.append("")
    v.append("module vrc7_exprom (input wire clk, input wire [7:0] a, output reg [9:0] q);")
    v.append(case("f", 10, EXP, 8, "(2^(x/256) - 1) * 1024"))
    v.append("    always @(posedge clk) q <= f(a);")
    v.append("endmodule")
    v.append("")
    v.append("// Combinational tables.")
    v.append("module vrc7_rom_patch (input wire [3:0] inst, input wire [2:0] idx, output wire [7:0] q);")
    v.append(case("f", 8, patch, 7, "VRC7 instruments 1-15, bytes 0-7 (index (inst-1)*8 + byte)"))
    v.append("    assign q = (inst == 4'd0) ? 8'd0 : f({inst - 4'd1, idx});")
    v.append("endmodule")
    v.append("")
    v.append("module vrc7_rom_kl (input wire [3:0] fnum4, input wire [2:0] blk, input wire [1:0] kl, output wire [6:0] q);")
    v.append(case("f", 7, kl, 9, "key-scale attenuation, index {kl, blk, fnum4}"))
    v.append("    assign q = f({kl, blk, fnum4});")
    v.append("endmodule")
    v.append("")
    v.append("module vrc7_rom_am (input wire [7:0] idx, output wire [3:0] q);")
    v.append(case("f", 4, AM, 8, "AM LFO pattern, 210 steps"))
    v.append("    assign q = f(idx);")
    v.append("endmodule")
    OUT.write_text("\n".join(v) + "\n")
    print(f"{OUT}: sine/exp/AM/instruments verified against the oracle; {len(kl)} KL entries")


if __name__ == "__main__":
    sys.exit(main())
