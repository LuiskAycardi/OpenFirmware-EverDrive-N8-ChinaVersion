#!/usr/bin/env python3
"""fmcheck.py — sample-exact equivalence test of hdl/rtl/vrc7_fm.v against the oracle (tools/fm/fmref).

Generates random but musically plausible VRC7 register-write scripts (instrument/volume, fnum/block,
key on/off, sustain, user-patch writes, the odd test-register write), runs the oracle and the RTL
testbench on each, and compares every sample.
  python3 -I tools/fm/fmcheck.py --fmref <fmref binary> [--seeds 20] [--samples 40000]
  python3 -I tools/fm/fmcheck.py --fmref <fmref binary> --golden     (rewrites the files of tb_vrc7_golden)
"""
import argparse
import pathlib
import random
import subprocess
import sys
import tempfile

ROOT = pathlib.Path(__file__).resolve().parents[2]
RTL = ["hdl/rtl/vrc7_fm.v", "hdl/rtl/vrc7_tables.v", "hdl/sim/tb_vrc7_fm.v"]


def script(seed, samples):
    rnd = random.Random(seed)
    w = []
    t = 0
    user = rnd.random() < 0.5
    if user or seed % 3 == 0:
        for r in range(8):
            w.append((0, r, rnd.randrange(256)))
    while True:
        t += rnd.choice([1, 2, 5, 20, 100, 300, 800, 2000])
        if t >= samples:
            break
        ch = rnd.randrange(6)
        k = rnd.random()
        if k < 0.25:
            w.append((t, 0x30 + ch, rnd.randrange(256)))
        elif k < 0.55:
            w.append((t, 0x10 + ch, rnd.randrange(256)))
            w.append((t, 0x20 + ch, rnd.randrange(64)))
        elif k < 0.75:
            w.append((t, 0x20 + ch, rnd.randrange(64) & ~0x10))
        elif k < 0.85:
            w.append((t, rnd.randrange(8), rnd.randrange(256)))
        elif k < 0.88:
            w.append((t, 0x0F, rnd.choice([0, 0, 0, 1, 2, 4, 8])))
        elif k < 0.90:
            w.append((t, rnd.choice([0x19, 0x1A, 0x29, 0x2B, 0x39, 0x3C, 0x0E, 0x16, 0x26, 0x36, 0x45]),
                      rnd.randrange(256)))
        else:
            w.append((t, 0x20 + ch, rnd.randrange(64) | 0x10))
    if rnd.random() < 0.7:
        w = [x for x in w if x[1] != 0x0F] + [(samples - 1, 0x0F, 0)]
    return f"{samples}\n" + "".join(f"{s} {r} {d}\n" for s, r, d in w)


def golden(fmref, seeds=(1, 3, 5, 7, 11), samples=4500):
    """Several short scripts concatenated into one (each shifted by k * samples) for tb_vrc7_golden."""
    w = []
    for k, seed in enumerate(seeds):
        body = script(seed, samples).splitlines()[1:]
        for ln in body:
            t, r, d = map(int, ln.split())
            w.append((t + k * samples, r, d))
    total = samples * len(seeds)
    # deterministic tail: user instrument with every modulator multiplier ML 0-15 (300 samples each)
    t0 = total
    w.append((t0, 0x0F, 0x00))                           # the random part may leave test bits set
    w.append((t0, 0x20, 0x00))
    for r, d in ((0x30, 0x00), (0x01, 0x01), (0x02, 0x00), (0x03, 0x05), (0x04, 0xF0), (0x05, 0xF0),
                 (0x06, 0x00), (0x07, 0x00), (0x10, 0x81), (0x20, 0x1A)):
        w.append((t0 + 1, r, d))
    for ml in range(16):
        w.append((t0 + 1 + ml * 300, 0x00, ml))
    total += 16 * 300 + 1
    txt =f"{total}\n" + "".join(f"{t} {r} {d}\n" for t, r, d in w)
    ref = subprocess.run([fmref], input=txt, capture_output=True, text=True, check=True).stdout.split()
    sim = ROOT / "hdl/sim"
    (sim / "vrc7_golden_w.hex").write_text(f"{len(w):08x}\n" + "".join(f"{t:04x}{r:02x}{d:02x}\n" for t, r, d in w))
    (sim / "vrc7_golden_ref.hex").write_text(f"{total:04x}\n" + "".join(f"{int(v) & 0xffff:04x}\n" for v in ref))
    (sim / "vrc7_golden.vh").write_text(f"// GENERATED by tools/fm/fmcheck.py --golden\n"
                                        f"localparam GOLD_NW = {len(w)};\nlocalparam GOLD_NS = {total};\n")
    print(f"{len(w)} escrituras, {total} muestras, pico {max(abs(int(v)) for v in ref)}")
    return 0


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--fmref", required=True)
    ap.add_argument("--seeds", type=int, default=20)
    ap.add_argument("--first", type=int, default=1)
    ap.add_argument("--samples", type=int, default=40000)
    ap.add_argument("--golden", action="store_true",
                    help="write hdl/sim/vrc7_golden_{w,ref}.hex (oracle samples for make sim) and exit")
    a = ap.parse_args()
    if a.golden:
        return golden(a.fmref)
    with tempfile.TemporaryDirectory() as td:
        td = pathlib.Path(td)
        vvp = td / "tb.vvp"
        subprocess.run(["iverilog", "-g2005", "-o", str(vvp)] + [str(ROOT / f) for f in RTL], check=True)
        bad = 0
        for seed in range(a.first, a.first + a.seeds):
            sc = td / "s.txt"
            sc.write_text(script(seed, a.samples))
            ref = subprocess.run([a.fmref], stdin=sc.open(), capture_output=True, text=True, check=True).stdout.split()
            out = td / "rtl.txt"
            subprocess.run(["vvp", "-n", str(vvp), f"+script={sc}", f"+out={out}"], check=True,
                           capture_output=True)
            rtl = out.read_text().split()
            n = min(len(ref), len(rtl))
            diff = next((i for i in range(n) if ref[i] != rtl[i]), None)
            peak = max(abs(int(x)) for x in ref) if ref else 0
            if diff is None and len(ref) == len(rtl):
                print(f"seed {seed}: OK {n} muestras (pico {peak})")
            else:
                bad += 1
                print(f"seed {seed}: DIFIERE en muestra {diff} ref={ref[diff:diff+5]} rtl={rtl[diff:diff+5]}")
                (ROOT / "hdl/out").mkdir(exist_ok=True)
                (ROOT / f"hdl/out/fm_seed{seed}.txt").write_text(sc.read_text())
        print("TODO IGUAL" if bad == 0 else f"{bad} semillas difieren")
        return 1 if bad else 0


if __name__ == "__main__":
    sys.exit(main())
